-- =====================================================================
-- 004: Modul Persuratan (penerbitan nomor surat, pengesahan manual)
-- Prasyarat: 001-003 sudah dijalankan. PostgreSQL 13+.
-- Aman dijalankan ulang (IF NOT EXISTS).
--
--   1. ALTER jabatan    : tambah can_sign
--   2. ref_options      : daftar pilihan (agama, pekerjaan, dusun, ...)
--   3. penduduk         : data induk warga (diisi hanya dari menu Penduduk)
--   4. jenis_surat      : cetakan surat (skema form + redaksi standar)
--   5. nomor_urut_surat : counter nomor surat per (cakupan, tahun)
--   6. surat            : transaksi surat (draft -> diterbitkan / dibatalkan)
-- =====================================================================
BEGIN;

-- 1. jabatan : penanda jabatan yang boleh menjadi penandatangan surat
ALTER TABLE jabatan
    ADD COLUMN IF NOT EXISTS can_sign SMALLINT NOT NULL DEFAULT 0 CHECK (can_sign IN (0, 1));

-- 2. ref_options : daftar pilihan sederhana per group_code
--    (AGAMA, PEKERJAAN, STATUS_PERKAWINAN, KEWARGANEGARAAN, DUSUN, PENDIDIKAN, HUBUNGAN_KELUARGA, ...)
--    Tabel lain menyimpan "code" (bukan id), mis. penduduk.agama = 'ISLAM'
CREATE TABLE IF NOT EXISTS ref_options (
    id_ref_option   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code      VARCHAR(50)  NOT NULL,
    code            VARCHAR(50)  NOT NULL,
    label           VARCHAR(150) NOT NULL,
    sort_order      INTEGER      NOT NULL DEFAULT 0,
    is_system       SMALLINT     NOT NULL DEFAULT 0 CHECK (is_system IN (0, 1)),
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_ref_options_group_code UNIQUE (group_code, code)
);

CREATE INDEX IF NOT EXISTS ix_ref_options_group ON ref_options (group_code, sort_order) WHERE is_active = 1;

-- 3. penduduk : data induk warga, sumber pencarian pemohon surat.
--    agama, pekerjaan, status_perkawinan, kewarganegaraan, dusun = code dari ref_options.
CREATE TABLE IF NOT EXISTS penduduk (
    id_penduduk       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nik               VARCHAR(16)  CHECK (nik IS NULL OR nik ~ '^[0-9]{16}$'),
    no_kk             VARCHAR(16)  CHECK (no_kk IS NULL OR no_kk ~ '^[0-9]{16}$'),
    full_name         VARCHAR(150) NOT NULL,
    tempat_lahir      VARCHAR(100),
    tanggal_lahir     DATE,
    jenis_kelamin     CHAR(1)      CHECK (jenis_kelamin IN ('L', 'P')),
    agama             VARCHAR(50),
    pekerjaan         VARCHAR(50),
    status_perkawinan VARCHAR(50),
    kewarganegaraan   VARCHAR(50)  DEFAULT 'WNI',
    dusun             VARCHAR(50),
    rt                VARCHAR(3),
    rw                VARCHAR(3),
    alamat            VARCHAR(255),
    is_active         SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by        INTEGER      REFERENCES users (id_user),
    updated_at        TIMESTAMPTZ,
    updated_by        INTEGER      REFERENCES users (id_user)
);

-- NIK unik jika terisi (data lama boleh belum punya NIK)
CREATE UNIQUE INDEX IF NOT EXISTS uq_penduduk_nik ON penduduk (nik) WHERE nik IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_penduduk_no_kk ON penduduk (no_kk) WHERE no_kk IS NOT NULL;
-- pencarian nama dengan awalan: WHERE lower(full_name) LIKE 'gugun%'
CREATE INDEX IF NOT EXISTS ix_penduduk_nama  ON penduduk (lower(full_name) text_pattern_ops);
CREATE INDEX IF NOT EXISTS ix_penduduk_dusun ON penduduk (dusun);

-- 4. jenis_surat : cetakan tiap jenis surat
--    skema_form   : {"sections":[{key,label,type: penduduk|fields|daftar|teks_bebas,...}]}
--    template_isi : HTML redaksi standar dengan placeholder {{ ... }}
--    persyaratan  : [{"nama":"KTP","wajib":1}, ...]
--    versi        : naik 1 setiap kali form/redaksi disimpan
CREATE TABLE IF NOT EXISTS jenis_surat (
    id_jenis_surat   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(30)  NOT NULL,
    name             VARCHAR(150) NOT NULL,
    kode_klasifikasi VARCHAR(30)  NOT NULL,
    skema_form       JSONB        NOT NULL DEFAULT '{"sections": []}'::jsonb
                     CHECK (jsonb_typeof(skema_form) = 'object'),
    template_isi     TEXT         NOT NULL DEFAULT '',
    persyaratan      JSONB        NOT NULL DEFAULT '[]'::jsonb
                     CHECK (jsonb_typeof(persyaratan) = 'array'),
    versi            INTEGER      NOT NULL DEFAULT 1 CHECK (versi >= 1),
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    is_active        SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       INTEGER      REFERENCES users (id_user),
    updated_at       TIMESTAMPTZ,
    updated_by       INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_jenis_surat_code UNIQUE (code)
);

-- 5. nomor_urut_surat : counter nomor surat. Hanya maju, tidak pernah dikurangi
--    (nomor surat yang dibatalkan tetap hangus).
--    cakupan : 'GLOBAL' atau code jenis surat (sesuai settings surat.cakupan_nomor)
--
--    Pengambilan nomor (di dalam transaksi penerbitan):
--      INSERT INTO nomor_urut_surat (cakupan, tahun, nomor_terakhir, updated_at)
--      VALUES (:cakupan, :tahun, 1, :now)
--      ON CONFLICT (cakupan, tahun)
--      DO UPDATE SET nomor_terakhir = nomor_urut_surat.nomor_terakhir + 1,
--                    updated_at     = :now
--      RETURNING nomor_terakhir;
CREATE TABLE IF NOT EXISTS nomor_urut_surat (
    id_nomor_urut_surat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cakupan             VARCHAR(30)  NOT NULL,
    tahun               SMALLINT     NOT NULL CHECK (tahun BETWEEN 2000 AND 2100),
    nomor_terakhir      INTEGER      NOT NULL DEFAULT 0 CHECK (nomor_terakhir >= 0),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_nomor_urut_surat UNIQUE (cakupan, tahun)
);

-- 6. surat : satu baris = satu surat keluar
--    status : draft -> diterbitkan ; draft/diterbitkan -> dibatalkan
--    id_penduduk opsional (NULL jika pemohon diisi manual / belum terdaftar).
--    Biodata semua pihak selalu tersimpan di data (snapshot).
--    nama_pemohon & nik_pemohon : pemohon utama, untuk daftar/pencarian/register.
--    skema_form & redaksi : salinan dari jenis_surat saat surat dibuat.
--    arsip_path : scan surat bertanda tangan & berstempel (mengunci surat).
CREATE TABLE IF NOT EXISTS surat (
    id_surat           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jenis_surat     INTEGER      NOT NULL REFERENCES jenis_surat (id_jenis_surat),
    id_penduduk        INTEGER      REFERENCES penduduk (id_penduduk),
    nama_pemohon       VARCHAR(150) NOT NULL,
    nik_pemohon        VARCHAR(16)  CHECK (nik_pemohon IS NULL OR nik_pemohon ~ '^[0-9]{16}$'),
    id_surat_diganti   INTEGER      REFERENCES surat (id_surat),

    -- status & nomor
    status             VARCHAR(20)  NOT NULL DEFAULT 'draft'
                       CHECK (status IN ('draft', 'diterbitkan', 'dibatalkan')),
    nomor_surat        VARCHAR(100),
    nomor_urut         INTEGER      CHECK (nomor_urut > 0),
    tanggal_surat      DATE,

    -- isi surat
    versi_template     INTEGER      NOT NULL,
    skema_form         JSONB        NOT NULL CHECK (jsonb_typeof(skema_form) = 'object'),
    redaksi            TEXT         NOT NULL,
    redaksi_diubah     SMALLINT     NOT NULL DEFAULT 0 CHECK (redaksi_diubah IN (0, 1)),
    data               JSONB        NOT NULL DEFAULT '{}'::jsonb
                       CHECK (jsonb_typeof(data) = 'object'),
    lampiran           JSONB        NOT NULL DEFAULT '[]'::jsonb
                       CHECK (jsonb_typeof(lampiran) = 'array'),

    -- penandatangan (tanda tangan & stempel basah dilakukan manual)
    id_penandatangan   INTEGER      REFERENCES pegawai (id_pegawai),
    atas_nama          SMALLINT     NOT NULL DEFAULT 0 CHECK (atas_nama IN (0, 1)),
    data_penandatangan JSONB,

    -- penerbitan & arsip
    diterbitkan_oleh   INTEGER      REFERENCES users (id_user),
    diterbitkan_pada   TIMESTAMPTZ,
    pdf_path           VARCHAR(255),
    arsip_path         VARCHAR(255),
    alasan_batal       TEXT,
    riwayat            JSONB        NOT NULL DEFAULT '[]'::jsonb
                       CHECK (jsonb_typeof(riwayat) = 'array'),

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         INTEGER      REFERENCES users (id_user),
    updated_at         TIMESTAMPTZ,
    updated_by         INTEGER      REFERENCES users (id_user),

    -- nomor surat tidak pernah dipakai dua kali (termasuk yang dibatalkan)
    CONSTRAINT uq_surat_nomor_surat UNIQUE (nomor_surat),

    -- draft belum boleh punya nomor
    CONSTRAINT ck_surat_draft_tanpa_nomor CHECK (
        status <> 'draft'
        OR (nomor_surat IS NULL AND nomor_urut IS NULL
            AND diterbitkan_oleh IS NULL AND diterbitkan_pada IS NULL)
    ),

    -- surat diterbitkan wajib lengkap data penerbitannya
    CONSTRAINT ck_surat_terbit_lengkap CHECK (
        status <> 'diterbitkan'
        OR (nomor_surat IS NOT NULL AND nomor_urut IS NOT NULL
            AND tanggal_surat IS NOT NULL AND id_penandatangan IS NOT NULL
            AND data_penandatangan IS NOT NULL
            AND diterbitkan_oleh IS NOT NULL AND diterbitkan_pada IS NOT NULL)
    ),

    -- pembatalan wajib ada alasan (nomor tetap tersimpan jika sudah terbit)
    CONSTRAINT ck_surat_batal_beralasan CHECK (
        status <> 'dibatalkan' OR alasan_batal IS NOT NULL
    ),

    -- scan arsip hanya untuk surat yang sudah bernomor
    CONSTRAINT ck_surat_arsip_bernomor CHECK (
        arsip_path IS NULL OR nomor_surat IS NOT NULL
    ),

    CONSTRAINT ck_surat_tidak_mengganti_diri CHECK (
        id_surat_diganti IS NULL OR id_surat_diganti <> id_surat
    )
);

CREATE INDEX IF NOT EXISTS ix_surat_jenis_tanggal ON surat (id_jenis_surat, tanggal_surat);  -- buku register per jenis
CREATE INDEX IF NOT EXISTS ix_surat_tanggal       ON surat (tanggal_surat);                  -- buku agenda surat keluar
CREATE INDEX IF NOT EXISTS ix_surat_status        ON surat (status);
CREATE INDEX IF NOT EXISTS ix_surat_id_penduduk   ON surat (id_penduduk) WHERE id_penduduk IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_surat_nik_pemohon   ON surat (nik_pemohon) WHERE nik_pemohon IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_surat_nama_pemohon  ON surat (lower(nama_pemohon) text_pattern_ops);
CREATE INDEX IF NOT EXISTS ix_surat_created_at    ON surat (created_at DESC);
CREATE INDEX IF NOT EXISTS ix_surat_diganti       ON surat (id_surat_diganti) WHERE id_surat_diganti IS NOT NULL;

COMMIT;

