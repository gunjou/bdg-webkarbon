-- =====================================================================
-- Sistem Desa Karang Bongkot - 001_init.sql
-- Modul: Login (users & roles) + Absensi
-- PostgreSQL 13+
--
-- Konvensi:
--   - PK  : id_<entitas>, IDENTITY
--   - FK  : nama sama dengan PK tujuan; peran lain pakai nama peran
--           (created_by, updated_by, reviewed_by -> users.id_user)
--   - Flag: SMALLINT 0/1 (1 = aktif / ya)
--   - Waktu: TIMESTAMPTZ. Set timezone database ke WITA:
--       ALTER DATABASE <nama_db> SET timezone = 'Asia/Makassar';
--   - updated_at / updated_by diisi oleh aplikasi pada setiap UPDATE
-- =====================================================================

BEGIN;

-- =====================================================================
-- 1. LOGIN
-- =====================================================================

-- ---------------------------------------------------------------------
-- users : akun login. id_pegawai diisi jika akun milik pegawai.
-- FK ke pegawai ditambahkan setelah tabel pegawai dibuat (lihat bawah).
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id_user         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pegawai      INTEGER,
    username        VARCHAR(50)  NOT NULL,
    email           VARCHAR(150),
    password_hash   VARCHAR(255) NOT NULL,
    kode_pemulihan  VARCHAR(12),
    last_login_at   TIMESTAMPTZ,
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_users_id_pegawai UNIQUE (id_pegawai)
);

-- username & email unik tanpa membedakan huruf besar/kecil
CREATE UNIQUE INDEX uq_users_username ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email    ON users (lower(email)) WHERE email IS NOT NULL;

-- ---------------------------------------------------------------------
-- roles : paket hak akses. permissions = array kode, mis.
--         ["absensi.self", "perizinan.review", "pegawai.manage"]
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id_role         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL,
    name            VARCHAR(100) NOT NULL,
    permissions     JSONB        NOT NULL DEFAULT '[]'::jsonb
                    CHECK (jsonb_typeof(permissions) = 'array'),
    is_system       SMALLINT     NOT NULL DEFAULT 0 CHECK (is_system IN (0, 1)),
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_roles_code UNIQUE (code)
);

-- ---------------------------------------------------------------------
-- user_roles : satu user bisa punya banyak role (hak akses = gabungan).
-- Mencabut role = DELETE baris.
-- ---------------------------------------------------------------------
CREATE TABLE user_roles (
    id_user_role    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user         INTEGER      NOT NULL REFERENCES users (id_user) ON DELETE CASCADE,
    id_role         INTEGER      NOT NULL REFERENCES roles (id_role),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_user_roles UNIQUE (id_user, id_role)
);

CREATE INDEX ix_user_roles_id_role ON user_roles (id_role);

-- ---------------------------------------------------------------------
-- login_failures : kendala login untuk username yang TERDAFTAR saja.
-- error_code (didefinisikan di aplikasi):
--   WRONG_PASSWORD, USER_INACTIVE, PEGAWAI_INACTIVE, NO_ACTIVE_ROLE, SERVER_ERROR
-- ---------------------------------------------------------------------
CREATE TABLE login_failures (
    id_login_failure BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user          INTEGER      NOT NULL REFERENCES users (id_user) ON DELETE CASCADE,
    error_code       VARCHAR(50)  NOT NULL,
    error_message    TEXT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_login_failures_user_time ON login_failures (id_user, created_at DESC);
CREATE INDEX ix_login_failures_code_time ON login_failures (error_code, created_at DESC);

-- ---------------------------------------------------------------------
-- settings : parameter sistem (key-value). Daftar key valid ada di kode.
-- ---------------------------------------------------------------------
CREATE TABLE settings (
    id_setting      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key             VARCHAR(100) NOT NULL,
    value           JSONB        NOT NULL,
    description     TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_settings_key UNIQUE (key)
);

-- =====================================================================
-- 2. MASTER ABSENSI & KEPEGAWAIAN
-- =====================================================================

-- ---------------------------------------------------------------------
-- jabatan
-- ---------------------------------------------------------------------
CREATE TABLE jabatan (
    id_jabatan      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    sort_order      INTEGER      NOT NULL DEFAULT 0,
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user)
);

CREATE UNIQUE INDEX uq_jabatan_name ON jabatan (lower(name));

-- ---------------------------------------------------------------------
-- lokasi_kantor : titik & radius lokasi absen yang sah
-- ---------------------------------------------------------------------
CREATE TABLE lokasi_kantor (
    id_lokasi_kantor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL,
    latitude         NUMERIC(9, 6) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude        NUMERIC(9, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius_meter     INTEGER       NOT NULL DEFAULT 100 CHECK (radius_meter > 0),
    is_active        SMALLINT      NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       INTEGER       REFERENCES users (id_user),
    updated_at       TIMESTAMPTZ,
    updated_by       INTEGER       REFERENCES users (id_user)
);

-- ---------------------------------------------------------------------
-- jadwal_kerja : jam kerja per hari dalam JSONB. Hari libur = null.
-- Contoh jadwal_harian:
-- {
--   "senin":  {"masuk": "07:30", "pulang": "15:30"},
--   "selasa": {"masuk": "07:30", "pulang": "15:30"},
--   "rabu":   {"masuk": "07:30", "pulang": "15:30"},
--   "kamis":  {"masuk": "07:30", "pulang": "15:30"},
--   "jumat":  {"masuk": "07:30", "pulang": "11:30"},
--   "sabtu":  null,
--   "minggu": null
-- }
-- ---------------------------------------------------------------------
CREATE TABLE jadwal_kerja (
    id_jadwal_kerja           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(100) NOT NULL,
    jadwal_harian             JSONB        NOT NULL
                              CHECK (jsonb_typeof(jadwal_harian) = 'object'),
    toleransi_terlambat_menit INTEGER      NOT NULL DEFAULT 0
                              CHECK (toleransi_terlambat_menit >= 0),
    is_active                 SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by                INTEGER      REFERENCES users (id_user),
    updated_at                TIMESTAMPTZ,
    updated_by                INTEGER      REFERENCES users (id_user)
);

-- ---------------------------------------------------------------------
-- hari_libur
-- ---------------------------------------------------------------------
CREATE TABLE hari_libur (
    id_hari_libur   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal         DATE         NOT NULL,
    name            VARCHAR(150) NOT NULL,
    jenis           VARCHAR(20)  NOT NULL DEFAULT 'nasional'
                    CHECK (jenis IN ('nasional', 'cuti_bersama', 'lokal')),
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user)
);

-- satu tanggal hanya boleh punya satu hari libur aktif
CREATE UNIQUE INDEX uq_hari_libur_tanggal ON hari_libur (tanggal) WHERE is_active = 1;

-- ---------------------------------------------------------------------
-- jenis_izin : sakit, izin, cuti, dinas luar, ...
-- ---------------------------------------------------------------------
CREATE TABLE jenis_izin (
    id_jenis_izin   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)  NOT NULL,
    name            VARCHAR(100) NOT NULL,
    butuh_lampiran  SMALLINT     NOT NULL DEFAULT 0 CHECK (butuh_lampiran IN (0, 1)),
    dihitung_hadir  SMALLINT     NOT NULL DEFAULT 0 CHECK (dihitung_hadir IN (0, 1)),
    is_active       SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER      REFERENCES users (id_user),
    updated_at      TIMESTAMPTZ,
    updated_by      INTEGER      REFERENCES users (id_user),
    CONSTRAINT uq_jenis_izin_code UNIQUE (code)
);

-- ---------------------------------------------------------------------
-- pegawai : data perangkat desa + data wajah (1 foto enrollment).
--   id_lokasi_kantor NULL = boleh absen di semua lokasi aktif
--   embedding NULL        = belum enrollment wajah (FACE_NOT_ENROLLED)
-- ---------------------------------------------------------------------
CREATE TABLE pegawai (
    id_pegawai       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jabatan       INTEGER      NOT NULL REFERENCES jabatan (id_jabatan),
    id_jadwal_kerja  INTEGER      REFERENCES jadwal_kerja (id_jadwal_kerja),
    nip              VARCHAR(30),
    full_name        VARCHAR(150) NOT NULL,
    phone            VARCHAR(20),
    photo_path       VARCHAR(255),
    embedding        REAL[]       CHECK (embedding IS NULL OR cardinality(embedding) > 0),
    is_active        SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       INTEGER      REFERENCES users (id_user),
    updated_at       TIMESTAMPTZ,
    updated_by       INTEGER      REFERENCES users (id_user)
);

CREATE UNIQUE INDEX uq_pegawai_nip ON pegawai (nip) WHERE nip IS NOT NULL;
CREATE INDEX ix_pegawai_id_jabatan       ON pegawai (id_jabatan);
CREATE INDEX ix_pegawai_id_jadwal_kerja  ON pegawai (id_jadwal_kerja);
CREATE INDEX ix_pegawai_id_lokasi_kantor ON pegawai (id_lokasi_kantor);

-- FK users -> pegawai (ditunda karena pegawai dibuat setelah users)
ALTER TABLE users
    ADD CONSTRAINT fk_users_id_pegawai
    FOREIGN KEY (id_pegawai) REFERENCES pegawai (id_pegawai);

-- =====================================================================
-- 3. TRANSAKSI ABSENSI
-- =====================================================================

-- ---------------------------------------------------------------------
-- absensi : hanya absen yang BERHASIL. Append-only.
--   jam_jadwal & terlambat_menit = snapshot saat absen
--   status: tepat_waktu / terlambat (masuk), tepat_waktu / pulang_cepat (pulang)
-- ---------------------------------------------------------------------
CREATE TABLE absensi (
    id_absensi       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pegawai       INTEGER        NOT NULL REFERENCES pegawai (id_pegawai),
    id_lokasi_kantor INTEGER        NOT NULL REFERENCES lokasi_kantor (id_lokasi_kantor),
    tanggal          DATE           NOT NULL,
    jenis            VARCHAR(10)    NOT NULL CHECK (jenis IN ('masuk', 'pulang')),
    waktu_absen      TIMESTAMPTZ    NOT NULL,
    latitude         NUMERIC(9, 6)  NOT NULL,
    longitude        NUMERIC(9, 6)  NOT NULL,
    akurasi_gps      NUMERIC(8, 2),
    jarak_meter      NUMERIC(10, 2),
    skor_wajah       NUMERIC(6, 4),
    photo_path       VARCHAR(255)   NOT NULL,
    jam_jadwal       TIME,
    terlambat_menit  INTEGER        NOT NULL DEFAULT 0 CHECK (terlambat_menit >= 0),
    status           VARCHAR(20)    NOT NULL
                     CHECK (status IN ('tepat_waktu', 'terlambat', 'pulang_cepat')),
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- satu pegawai hanya boleh 1x absen masuk & 1x absen pulang per hari
    CONSTRAINT uq_absensi_pegawai_tanggal_jenis UNIQUE (id_pegawai, tanggal, jenis)
);

CREATE INDEX ix_absensi_tanggal ON absensi (tanggal);

-- ---------------------------------------------------------------------
-- absensi_gagal : semua percobaan absen yang gagal (client & server).
--   stage      : GPS, CAMERA, LOCATION, FACE, SCHEDULE, SYSTEM
--   error_code : didefinisikan di aplikasi, mis. GPS_PERMISSION_DENIED,
--                OUTSIDE_RADIUS, FACE_NOT_MATCH, OUTSIDE_TIME_WINDOW, ...
--   jenis      : boleh NULL jika gagal sebelum jenis absen ditentukan
--   photo_path : hanya diisi untuk kegagalan tahap FACE
-- ---------------------------------------------------------------------
CREATE TABLE absensi_gagal (
    id_absensi_gagal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pegawai       INTEGER        NOT NULL REFERENCES pegawai (id_pegawai),
    id_lokasi_kantor INTEGER        REFERENCES lokasi_kantor (id_lokasi_kantor),
    jenis            VARCHAR(10)    CHECK (jenis IN ('masuk', 'pulang')),
    source           VARCHAR(10)    NOT NULL CHECK (source IN ('client', 'server')),
    stage            VARCHAR(20)    NOT NULL
                     CHECK (stage IN ('GPS', 'CAMERA', 'LOCATION', 'FACE', 'SCHEDULE', 'SYSTEM')),
    error_code       VARCHAR(50)    NOT NULL,
    error_message    TEXT,
    latitude         NUMERIC(9, 6),
    longitude        NUMERIC(9, 6),
    akurasi_gps      NUMERIC(8, 2),
    jarak_meter      NUMERIC(10, 2),
    skor_wajah       NUMERIC(6, 4),
    photo_path       VARCHAR(255),
    detail           JSONB,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX ix_absensi_gagal_pegawai_time ON absensi_gagal (id_pegawai, created_at DESC);
CREATE INDEX ix_absensi_gagal_code_time    ON absensi_gagal (error_code, created_at DESC);
CREATE INDEX ix_absensi_gagal_time         ON absensi_gagal (created_at DESC);

-- ---------------------------------------------------------------------
-- perizinan : pengajuan koreksi absen & izin oleh pegawai.
--   jenis_pengajuan = 'izin'    -> wajib id_jenis_izin
--   jenis_pengajuan = 'koreksi' -> wajib jenis_absen & jam_koreksi,
--                                  dan hanya untuk satu tanggal
-- ---------------------------------------------------------------------
CREATE TABLE perizinan (
    id_perizinan     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pegawai       INTEGER      NOT NULL REFERENCES pegawai (id_pegawai),
    id_jenis_izin    INTEGER      REFERENCES jenis_izin (id_jenis_izin),
    jenis_pengajuan  VARCHAR(10)  NOT NULL CHECK (jenis_pengajuan IN ('koreksi', 'izin')),
    jenis_absen      VARCHAR(10)  CHECK (jenis_absen IN ('masuk', 'pulang')),
    tanggal_mulai    DATE         NOT NULL,
    tanggal_selesai  DATE         NOT NULL,
    jam_koreksi      TIME,
    alasan           TEXT         NOT NULL,
    lampiran_path    VARCHAR(255),
    status           VARCHAR(15)  NOT NULL DEFAULT 'diajukan'
                     CHECK (status IN ('diajukan', 'disetujui', 'ditolak', 'dibatalkan')),
    reviewed_by      INTEGER      REFERENCES users (id_user),
    reviewed_at      TIMESTAMPTZ,
    catatan_peninjau TEXT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       INTEGER      REFERENCES users (id_user),
    updated_at       TIMESTAMPTZ,
    updated_by       INTEGER      REFERENCES users (id_user),

    CONSTRAINT ck_perizinan_rentang_tanggal
        CHECK (tanggal_selesai >= tanggal_mulai),
    CONSTRAINT ck_perizinan_izin
        CHECK (jenis_pengajuan <> 'izin'
               OR (id_jenis_izin IS NOT NULL AND jenis_absen IS NULL AND jam_koreksi IS NULL)),
    CONSTRAINT ck_perizinan_koreksi
        CHECK (jenis_pengajuan <> 'koreksi'
               OR (id_jenis_izin IS NULL AND jenis_absen IS NOT NULL
                   AND jam_koreksi IS NOT NULL AND tanggal_mulai = tanggal_selesai)),
    CONSTRAINT ck_perizinan_review
        CHECK (status IN ('diajukan', 'dibatalkan')
               OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);

CREATE INDEX ix_perizinan_pegawai_tanggal ON perizinan (id_pegawai, tanggal_mulai, tanggal_selesai);
CREATE INDEX ix_perizinan_status          ON perizinan (status) WHERE status = 'diajukan';

COMMIT;
